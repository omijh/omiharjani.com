const aboutLineIds = ['about-line1', 'about-line2', 'about-line3', 'about-line4'];
const pillNames = ['pill1', 'pill2', 'pill3', 'pill4', 'pill5', 'pill6', 'pill7'];
const themeOrder = ['system', 'light', 'dark'];

let activeLang = 'en';

function applyLanguage(lang) {
  const t = translations[lang];
  if (!t) return;
  activeLang = lang;

  fieldMappings.forEach(([elId, key]) => {
    const el = document.getElementById(elId);
    if (el && t[key]) el.textContent = t[key];
  });

  aboutLineIds.forEach((id, idx) => {
    const el = document.getElementById(id);
    if (el && t.aboutLines[idx]) el.textContent = t.aboutLines[idx];
  });

  pillNames.forEach((name, idx) => {
    const el = document.querySelector(`[data-pill="${name}"]`);
    if (el && t.pills[idx]) el.textContent = t.pills[idx];
  });

  Object.keys(t.seasonLabels).forEach((sKey) => {
    const labelEl = document.querySelector(`[data-season-label="${sKey}"]`);
    if (labelEl) labelEl.textContent = t.seasonLabels[sKey];
  });

  const seasonSwitcher = document.getElementById('season-switcher');
  if (seasonSwitcher && t.seasonGroupLabel) {
    seasonSwitcher.setAttribute('aria-label', t.seasonGroupLabel);
  }

  document.querySelectorAll('.details-toggle').forEach((btn) => {
    const expanded = btn.getAttribute('aria-expanded') === 'true';
    btn.textContent = expanded ? t.detailsHide : t.detailsShow;
  });

  document.documentElement.lang = lang === 'ja' ? 'ja' : 'en';

  const langToggle = document.getElementById('lang-toggle');
  if (langToggle && t.langAriaLabel) {
    langToggle.setAttribute('aria-label', t.langAriaLabel);
  }

  document.querySelectorAll('[data-email]').forEach((el) => {
    if (t.emailLabel) {
      el.setAttribute('aria-label', t.emailLabel);
      el.setAttribute('title', t.emailLabel);
    }
  });

  const cmdInput = document.getElementById('cmd-input');
  if (cmdInput && t.cmdPlaceholder) {
    cmdInput.setAttribute('placeholder', t.cmdPlaceholder);
  }

  const cmdFooterTrigger = document.getElementById('cmd-open-footer');
  if (cmdFooterTrigger && t.cmdOpenLabel) {
    cmdFooterTrigger.setAttribute('aria-label', t.cmdOpenLabel);
  }

  const enSpan = document.querySelector('#lang-toggle .en');
  const jaSpan = document.querySelector('#lang-toggle .ja');
  if (enSpan && jaSpan) {
    enSpan.classList.toggle('active', lang === 'en');
    jaSpan.classList.toggle('active', lang === 'ja');
  }

  updateThemeLabel(getPreferredTheme(), lang);
}

function setupFadeIns() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );
  document.querySelectorAll('.fade-in').forEach((el) => observer.observe(el));
}

function setYear() {
  const yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = new Date().getFullYear();
}

function updateTokyoTime() {
  const el = document.getElementById('tokyo-time');
  if (!el) return;
  try {
    const formatted = new Intl.DateTimeFormat('en-US', {
      timeZone: 'Asia/Tokyo',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).format(new Date());
    el.textContent = `JST ${formatted}`;
  } catch {
    el.hidden = true;
  }
}

function updateThemeLabel(mode, lang) {
  const btn = document.getElementById('theme-toggle');
  if (!btn) return;
  const t = translations[lang || activeLang] || translations.en;
  const label = (t.themeLabels && t.themeLabels[mode]) || 'Auto';
  const prefix = t.themePrefix || 'Theme';
  const hint = t.themeHint || 'click to switch';
  btn.setAttribute('aria-label', `${prefix}: ${label}`);
  btn.setAttribute('title', `${prefix}: ${label} (${hint})`);
}

function cycleTheme() {
  const current = getPreferredTheme();
  const idx = themeOrder.indexOf(current);
  const next = themeOrder[(idx + 1) % themeOrder.length];
  if (next === 'system') {
    localStorage.removeItem('theme');
  } else {
    localStorage.setItem('theme', next);
  }
  applySeason(getCurrentSeason());
  updateThemeLabel(next, activeLang);
}

function showToast(message) {
  document.querySelectorAll('.toast').forEach((el) => el.remove());
  const toast = document.createElement('div');
  toast.className = 'toast';
  toast.setAttribute('role', 'status');
  toast.textContent = message;
  document.body.appendChild(toast);
  requestAnimationFrame(() => toast.classList.add('show'));
  setTimeout(() => {
    toast.classList.remove('show');
    setTimeout(() => toast.remove(), 220);
  }, 1500);
}

async function copyEmailAddress() {
  const _user = 'omiharjani';
  const _domain = 'gmail.com';
  const email = `${_user}@${_domain}`;
  try {
    await navigator.clipboard.writeText(email);
    const t = translations[activeLang] || translations.en;
    showToast(t.emailCopied || 'Copied!');
  } catch {
    window.location.href = `mailto:${email}`;
  }
}

function syncSeasonButtons(seasonKey) {
  document.querySelectorAll('.season-btn').forEach((btn) => {
    const isActive = btn.getAttribute('data-season') === seasonKey;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
  });
}

function setupSeasonSwitcher() {
  syncSeasonButtons(getCurrentSeason());

  document.querySelectorAll('.season-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      const season = btn.getAttribute('data-season');
      if (season && typeof setSeasonOverride === 'function') {
        setSeasonOverride(season);
        syncSeasonButtons(season);
      }
    });
  });

  window.addEventListener('seasonchange', (event) => {
    if (event.detail && event.detail.season) {
      syncSeasonButtons(event.detail.season);
    }
  });
}

function setupProjectDetails() {
  document.querySelectorAll('.details-toggle').forEach((btn) => {
    btn.addEventListener('click', () => {
      const targetId = btn.getAttribute('aria-controls');
      const panel = targetId ? document.getElementById(targetId) : null;
      if (!panel) return;
      const expanded = btn.getAttribute('aria-expanded') === 'true';
      const nextExpanded = !expanded;
      btn.setAttribute('aria-expanded', nextExpanded ? 'true' : 'false');
      panel.hidden = !nextExpanded;
      const t = translations[activeLang] || translations.en;
      btn.textContent = nextExpanded ? t.detailsHide : t.detailsShow;
    });
  });
}

function setupCommandPalette(toggleLangFn) {
  const backdrop = document.getElementById('cmd-palette');
  const input = document.getElementById('cmd-input');
  const list = document.getElementById('cmd-list');
  const empty = document.getElementById('cmd-empty');
  const closeBtn = document.getElementById('cmd-close');
  if (!backdrop || !input || !list || !empty) return;

  const isApple = /Mac|iPhone|iPad|iPod/i.test(navigator.platform || navigator.userAgent || '');
  const shortcutLabel = isApple ? '⌘K' : 'Ctrl K';
  const kbdEl = document.getElementById('cmd-kbd');
  if (kbdEl) kbdEl.textContent = shortcutLabel;

  let selectedIndex = 0;
  let filteredCommands = [];
  let previousFocus = null;

  function getCommands() {
    const t = translations[activeLang] || translations.en;
    const cat = t.cmdCategories;
    const items = t.cmdItems;
    const activeSeason = getCurrentSeason();
    return [
      { id: 'spring', icon: '🌸', label: items.spring, category: cat.season, isCurrent: activeSeason === 'spring', keepOpen: true, run: () => setSeasonOverride('spring') },
      { id: 'summer', icon: '☀️', label: items.summer, category: cat.season, isCurrent: activeSeason === 'summer', keepOpen: true, run: () => setSeasonOverride('summer') },
      { id: 'autumn', icon: '🍂', label: items.autumn, category: cat.season, isCurrent: activeSeason === 'autumn', keepOpen: true, run: () => setSeasonOverride('autumn') },
      { id: 'winter', icon: '❄️', label: items.winter, category: cat.season, isCurrent: activeSeason === 'winter', keepOpen: true, run: () => setSeasonOverride('winter') },
      { id: 'theme', icon: '🌗', label: items.theme, category: cat.appearance, keepOpen: true, run: () => cycleTheme() },
      { id: 'lang', icon: '🌐', label: items.lang, category: cat.appearance, keepOpen: true, run: () => toggleLangFn() },
      { id: 'email', icon: '✉️', label: items.email, category: cat.action, run: () => copyEmailAddress() },
      { id: 'qr', icon: '🪪', label: items.qr, category: cat.action, run: () => { window.location.href = '/qr/'; } },
      { id: 'uttayo', icon: '🛍️', label: items.uttayo, category: cat.project, run: () => window.open('https://uttayo.com', '_blank', 'noopener,noreferrer') },
      { id: 'gomi', icon: '♻️', label: items.gomi, category: cat.project, run: () => window.open('https://gomihelper.com', '_blank', 'noopener,noreferrer') },
      { id: 'podcast', icon: '🎙️', label: items.podcast, category: cat.project, run: () => window.open('https://podcasts.apple.com/us/podcast/jonny-omi-show/id1500310491', '_blank', 'noopener,noreferrer') },
      { id: 'github', icon: '💻', label: items.github, category: cat.link, run: () => window.open('https://github.com/omijh', '_blank', 'noopener,noreferrer') },
      { id: 'linkedin', icon: '💼', label: items.linkedin, category: cat.link, run: () => window.open('https://www.linkedin.com/in/supernerd', '_blank', 'noopener,noreferrer') },
      { id: 'x', icon: '𝕏', label: items.x, category: cat.link, run: () => window.open('https://x.com/omiharjani', '_blank', 'noopener,noreferrer') },
    ];
  }

  function executeCommand(cmd) {
    if (cmd.keepOpen) {
      cmd.run();
      renderList();
    } else {
      closePalette();
      cmd.run();
    }
  }

  function renderList() {
    const query = input.value.trim().toLowerCase();
    const commands = getCommands();
    filteredCommands = query
      ? commands.filter((c) => c.label.toLowerCase().includes(query) || c.category.toLowerCase().includes(query) || c.id.includes(query))
      : commands;

    if (selectedIndex >= filteredCommands.length) {
      selectedIndex = Math.max(0, filteredCommands.length - 1);
    }

    list.textContent = '';
    empty.hidden = filteredCommands.length > 0;

    filteredCommands.forEach((cmd, idx) => {
      const li = document.createElement('li');
      li.className = 'cmd-item' + (idx === selectedIndex ? ' active' : '') + (cmd.isCurrent ? ' is-current' : '');
      li.setAttribute('role', 'option');
      li.setAttribute('aria-selected', idx === selectedIndex ? 'true' : 'false');

      const left = document.createElement('span');
      left.className = 'cmd-item-left';

      const icon = document.createElement('span');
      icon.className = 'cmd-item-icon';
      icon.setAttribute('aria-hidden', 'true');
      icon.textContent = cmd.icon;

      const label = document.createElement('span');
      label.className = 'cmd-item-label';
      label.textContent = cmd.label;

      left.appendChild(icon);
      left.appendChild(label);

      const right = document.createElement('span');
      right.className = 'cmd-item-right';

      if (cmd.isCurrent) {
        const check = document.createElement('span');
        check.className = 'cmd-check';
        check.setAttribute('aria-hidden', 'true');
        check.textContent = '✓';
        right.appendChild(check);
      }

      const cat = document.createElement('span');
      cat.className = 'cmd-item-cat';
      cat.textContent = cmd.category;
      right.appendChild(cat);

      li.appendChild(left);
      li.appendChild(right);

      li.addEventListener('mouseenter', () => {
        selectedIndex = idx;
        updateActiveItem(false);
      });
      li.addEventListener('click', () => {
        executeCommand(cmd);
      });

      list.appendChild(li);
    });
  }

  function updateActiveItem(shouldScroll) {
    const nodes = list.querySelectorAll('.cmd-item');
    nodes.forEach((node, idx) => {
      const isSelected = idx === selectedIndex;
      node.classList.toggle('active', isSelected);
      node.setAttribute('aria-selected', isSelected ? 'true' : 'false');
      if (isSelected && shouldScroll) node.scrollIntoView({ block: 'nearest' });
    });
  }

  function openPalette() {
    previousFocus = document.activeElement;
    input.value = '';
    selectedIndex = 0;
    backdrop.hidden = false;
    renderList();
    requestAnimationFrame(() => input.focus());
  }

  function closePalette() {
    if (backdrop.hidden) return;
    backdrop.hidden = true;
    if (previousFocus && typeof previousFocus.focus === 'function') {
      previousFocus.focus();
    }
  }

  input.addEventListener('input', () => {
    selectedIndex = 0;
    renderList();
  });

  input.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowDown') {
      e.preventDefault();
      if (filteredCommands.length) {
        selectedIndex = (selectedIndex + 1) % filteredCommands.length;
        updateActiveItem(true);
      }
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      if (filteredCommands.length) {
        selectedIndex = (selectedIndex - 1 + filteredCommands.length) % filteredCommands.length;
        updateActiveItem(true);
      }
    } else if (e.key === 'Enter') {
      e.preventDefault();
      const chosen = filteredCommands[selectedIndex];
      if (chosen) {
        executeCommand(chosen);
      }
    } else if (e.key === 'Escape') {
      e.preventDefault();
      closePalette();
    }
  });

  document.addEventListener('keydown', (e) => {
    if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
      e.preventDefault();
      if (backdrop.hidden) openPalette();
      else closePalette();
    } else if (e.key === 'Escape' && !backdrop.hidden) {
      e.preventDefault();
      closePalette();
    }
  });

  backdrop.addEventListener('click', (e) => {
    if (e.target === backdrop) closePalette();
  });

  if (closeBtn) closeBtn.addEventListener('click', closePalette);
  const footerTrigger = document.getElementById('cmd-open-footer');
  if (footerTrigger) footerTrigger.addEventListener('click', openPalette);
}

